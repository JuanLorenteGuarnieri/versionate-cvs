/**
 * Traduce una clave de la UI al idioma especificado.
 * Si la clave o el idioma no existen, devuelve la clave misma (fallback).
 */
export function translateUI(key: keyof typeof UI_TRANSLATIONS, lang: string): string {
  const langMessages = UI_TRANSLATIONS[key];
  if (langMessages && langMessages[lang]) {
    return langMessages[lang];
  }
  // Fallback to English if available, otherwise return the key
  const fallback = UI_TRANSLATIONS[key]?.en ?? key as string;
  return fallback;
}

/**
 * Obtiene el nombre legible de un código de idioma para mostrar en el selector.
 */
export function getUILanguageDisplayName(lang: string): string {
  return UI_LANGUAGE_NAMES[lang] ?? lang;
}